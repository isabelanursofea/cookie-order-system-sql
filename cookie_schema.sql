-- ===== CREATE TABLES =====
CREATE TABLE ADMIN (
  ADMIN_ID NUMBER PRIMARY KEY,
  ADMIN_NAME VARCHAR2(100),
  ADMIN_EMAIL VARCHAR2(100),
  ADMIN_PASSWORD VARCHAR2(100)
);

CREATE TABLE CUSTOMER (
  CUSTOMER_ID NUMBER PRIMARY KEY,
  CUSTOMER_NAME VARCHAR2(100),
  EMAIL VARCHAR2(100),
  PHONE_NUMBER VARCHAR2(15)
);

CREATE TABLE COOKIE (
  COOKIE_ID NUMBER PRIMARY KEY,
  COOKIE_NAME VARCHAR2(150),
  COOKIE_DESCRIPTION VARCHAR2(255),
  PRICE_PER_UNIT NUMBER(6,2),
  AVAILABLE_STOCK NUMBER,
  COOKIE_IMAGE BLOB,
  ADMIN_ID NUMBER,
  CONSTRAINT fk_ADMIN_ID FOREIGN KEY (ADMIN_ID) REFERENCES ADMIN(ADMIN_ID)
);

CREATE TABLE DELIVERY (
  DELIVERY_ID NUMBER PRIMARY KEY,
  DELIVERY_DATE DATE,
  DELIVERY_METHOD VARCHAR2(50),
  DELIVERY_STATUS VARCHAR2(50),
  ADMIN_ID NUMBER,
  CONSTRAINT fk_DELIVERY_ADMIN FOREIGN KEY (ADMIN_ID) REFERENCES ADMIN(ADMIN_ID)
);

CREATE TABLE CUSTOMER_ORDER (
  ORDER_ID NUMBER PRIMARY KEY,
  CUSTOMER_ID NUMBER,
  DELIVERY_ID NUMBER,
  ORDER_DATE DATE,
  TOTAL_AMOUNT NUMBER(8,2),
  ORDER_STATUS VARCHAR2(50),
  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
  FOREIGN KEY (DELIVERY_ID) REFERENCES DELIVERY(DELIVERY_ID)
);

CREATE TABLE ORDER_COOKIE (
  ORDER_COOKIE_ID NUMBER PRIMARY KEY,
  ORDER_ID NUMBER,
  COOKIE_ID NUMBER,
  QUANTITY NUMBER,
  SUBTOTAL NUMBER(8,2),
  DELIVERY_ADDRESS VARCHAR2(255),
  FOREIGN KEY (ORDER_ID) REFERENCES CUSTOMER_ORDER(ORDER_ID),
  FOREIGN KEY (COOKIE_ID) REFERENCES COOKIE(COOKIE_ID)
);

CREATE TABLE METHOD_PAY (
  PAYMENT_METHOD VARCHAR2(50) PRIMARY KEY
);

CREATE TABLE PAYMENT (
  PAYMENT_ID NUMBER PRIMARY KEY,
  ORDER_ID NUMBER,
  PAYMENT_METHOD VARCHAR2(255),
  PAYMENT_DATE DATE,
  PAYMENT_STATUS VARCHAR2(50),
  FOREIGN KEY (ORDER_ID) REFERENCES CUSTOMER_ORDER(ORDER_ID),
  FOREIGN KEY (PAYMENT_METHOD) REFERENCES METHOD_PAY(PAYMENT_METHOD)
);

